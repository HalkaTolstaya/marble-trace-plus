// Writes THIRD_PARTY_NOTICES.md: the licence of every crate and npm package
// shipped in the app, plus the full texts of the upstream projects this fork
// is built on. Run after dependency changes: `npm run notices`.
//
// Crates come from `cargo metadata` for the Windows target (normal deps only);
// npm packages from package-lock.json, production dependencies only.
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const ROOT = join(import.meta.dirname, '..');

